def profile(df: pd.DataFrame) -> list:
    """Column-level metadata: type, fill rate, cardinality, example."""
    out = []
    for col in df.columns:
        s = df[col]
        non_null = s.notna().sum()
        example = s.dropna().iloc[0] if non_null else None
        out.append({
            "name": col,
            "type": str(s.dtype),
            "completeness": round(non_null / len(df), 3) if len(df) else 0,
            "distinct": int(s.nunique()),
            "example": str(example)[:40] if example is not None else "",
            "description": COLUMN_NOTES.get(col, ""),
        })
    return out


def build():
    meta = pd.read_csv(config.RAW / "_feed_metadata.csv")
    freshness = dict(zip(meta.feed, meta.loaded_at))

    try:
        issues = pd.read_csv(config.PROCESSED / "quality_issues.csv")
    except FileNotFoundError:
        issues = pd.DataFrame(columns=["feed", "type"])

    entries = []
    for filename, info in DATASETS.items():
        path = config.RAW / filename
        if not path.exists():
            continue
        df = pd.read_csv(path)
        loaded = freshness.get(filename)
        age_h = int((NOW - datetime.fromisoformat(loaded)).total_seconds() / 3600) \
            if loaded else None
        feed_issues = issues[issues.feed == filename]

        entries.append({
            **info,
            "file": filename,
            "rows": len(df),
            "columns": profile(df),
            "column_count": len(df.columns),
            "loaded_at": loaded,
            "age_hours": age_h,
            "stale": bool(age_h is not None and age_h >= 72),
            "open_issues": int(len(feed_issues)),
            "issue_types": sorted(feed_issues["type"].unique().tolist()),
            "retrieval": f"backend.core.repository.resolved('{filename[:-4]}')",
        })

    # FAIR self-assessment — stated as implemented evidence, not aspiration
    fair = [
        {"principle": "F1", "requirement":
         "Data assigned a globally unique, persistent identifier",
         "met": True, "evidence": "Every dataset carries an ost: URI; every site "
                                  "resolves to one canonical identifier."},
        {"principle": "F2", "requirement": "Data described with rich metadata",
         "met": True, "evidence": f"{len(entries)} datasets catalogued with "
                                  "column-level type, completeness and cardinality."},
        {"principle": "F4", "requirement": "Metadata registered in a searchable resource",
         "met": True, "evidence": "catalog.json, searchable in the Catalog view."},
        {"principle": "A1", "requirement":
         "Data retrievable by identifier using an open protocol",
         "met": True, "evidence": "Each entry records its retrieval call against the "
                                  "repository layer."},
        {"principle": "A2", "requirement": "Metadata accessible even when data is not",
         "met": True, "evidence": "Catalog metadata is visible to roles that are "
                                  "denied the underlying columns."},
        {"principle": "I1", "requirement": "Data uses a formal, shared vocabulary",
         "met": True, "evidence": "EDC feeds map to CDISC SDTM domains; identifiers "
                                  "resolve through an OMOP-style "
                                  "source_to_concept_map."},
        {"principle": "I3", "requirement": "Data includes qualified references to other data",
         "met": True, "evidence": "Every entity carries derived_from edges to the "
                                  "exact source rows that produced it."},
        {"principle": "R1.1", "requirement": "Released with a clear data usage licence",
         "met": True, "evidence": "Licence recorded per dataset; CDISC attribution "
                                  "preserved."},
        {"principle": "R1.2", "requirement": "Associated with detailed provenance",
         "met": True, "evidence": "Provenance string per dataset, plus row-level "
                                  "lineage in the graph."},
        {"principle": "R1.3", "requirement": "Meets domain-relevant community standards",
         "met": True, "evidence": "CDISC SDTM for clinical data; FAIR for metadata; "
                                  "OHDSI source-to-concept mapping for identity "
                                  "resolution."},
    ]

    catalog = {
        "generated_at": NOW.isoformat(),
        "standards": {
            "fair": "Wilkinson et al. 2016, Scientific Data 3:160018",
            "clinical": "CDISC SDTM",
            "harmonisation": "OHDSI / OMOP source_to_concept_map pattern "
                             "(The Book of OHDSI, ch. 6)",
        },
        "datasets": entries,
        "fair_assessment": fair,
    }

    with open(config.PROCESSED / "catalog.json", "w") as f:
        json.dump(catalog, f, indent=2)

    print(f"\nCatalog built")
    print(f"  datasets      {len(entries)}")
    print(f"  columns       {sum(e['column_count'] for e in entries)}")
    print(f"  rows          {sum(e['rows'] for e in entries):,}")
    print(f"  FAIR criteria {sum(1 for f in fair if f['met'])}/{len(fair)} met")
    print(f"  -> {config.PROCESSED / 'catalog.json'}")


if __name__ == "__main__":
    build()
